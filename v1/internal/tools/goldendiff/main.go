// Command goldendiff writes docs/golden-diff.md: how each golden file of the
// rewrite's suite (test/v1/local) differs from its namesake in the old CLI's
// suite (test/v0/local). Run it with `make -C v1 golden-diff`.
//
// Files are compared on what the command printed and returned, decoded from
// YAML, so a change of quoting style doesn't show. Every changed or new golden
// needs a note in notes.go that says why; the command fails without one.
//
// The tool only serves the refactoring. It is deleted at the switch (step 15
// of docs/project-structure.md), with test/v0, docs/golden-diff.md and the
// golden-diff target.
package main

import (
	"flag"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"gopkg.in/yaml.v3"
)

func main() {
	if err := run(os.Args[1:]); err != nil {
		fmt.Fprintln(os.Stderr, "goldendiff:", err)
		os.Exit(1)
	}
}

// run parses args, reads both golden trees and writes the document.
func run(args []string) error {
	flags := flag.NewFlagSet("goldendiff", flag.ContinueOnError)
	flags.SetOutput(io.Discard) // run returns the parse error; main prints it
	v0Dir := flags.String("v0", "test/v0/local/testdata/golden", "golden files of the old CLI")
	v1Dir := flags.String("v1", "test/v1/local/testdata/golden", "golden files of the rewrite")
	out := flags.String("o", "docs/golden-diff.md", "document to write")
	if err := flags.Parse(args); err != nil {
		return err
	}
	v0, err := load(*v0Dir)
	if err != nil {
		return err
	}
	v1, err := load(*v1Dir)
	if err != nil {
		return err
	}
	doc, err := render(v0, v1, notes())
	if err != nil {
		return err
	}
	return os.WriteFile(*out, []byte(doc), 0o644) //nolint:gosec // a docs file, readable by everyone
}

// golden holds the fields of a golden file, as the suites write them.
type golden struct {
	Command string            `yaml:"command"`
	Exit    int               `yaml:"exit"`
	Stdout  string            `yaml:"stdout"`
	Stderr  string            `yaml:"stderr"`
	Files   map[string]string `yaml:"files,omitempty"`
}

// load reads every <Test>/<row>.yaml under root, keyed by "<Test>/<row>".
func load(root string) (map[string]golden, error) {
	goldens := map[string]golden{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || filepath.Ext(path) != ".yaml" {
			return err
		}
		data, err := os.ReadFile(path) //nolint:gosec // a path under the golden dir
		if err != nil {
			return err
		}
		var g golden
		if err = yaml.Unmarshal(data, &g); err != nil {
			return fmt.Errorf("%s: %w", path, err)
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		goldens[strings.TrimSuffix(filepath.ToSlash(rel), ".yaml")] = g
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("read the golden files: %w", err)
	}
	return goldens, nil
}

// render returns the document. Every changed or new golden needs a note, and
// every note a changed or new golden.
func render(v0, v1 map[string]golden, notes map[string]string) (string, error) {
	var changed, added, same, onlyV0 []string
	for _, k := range slices.Sorted(maps.Keys(v1)) {
		old, ok := v0[k]
		switch {
		case !ok:
			added = append(added, k)
		case equal(old, v1[k]):
			same = append(same, k)
		default:
			changed = append(changed, k)
		}
	}
	for _, k := range slices.Sorted(maps.Keys(v0)) {
		if _, ok := v1[k]; !ok {
			onlyV0 = append(onlyV0, k)
		}
	}
	if err := checkNotes(slices.Concat(changed, added), notes); err != nil {
		return "", err
	}

	var b strings.Builder
	b.WriteString(header)
	fmt.Fprintf(&b, "| Changed | New in v1 | Identical | Only in v0 |\n|---|---|---|---|\n| %d | %d | %d | %d |\n",
		len(changed), len(added), len(same), len(onlyV0))

	b.WriteString("\n## Changed\n")
	if len(changed) == 0 {
		b.WriteString("\nNone.\n")
	}
	for _, k := range changed {
		writeChanged(&b, k, v0[k], v1[k], notes[k])
	}

	b.WriteString("\n## New in v1\n")
	if len(added) == 0 {
		b.WriteString("\nNone.\n")
	}
	for _, k := range added {
		writeAdded(&b, k, v1[k], notes[k])
	}

	if len(same) > 0 {
		b.WriteString("\n## Identical\n\n")
		for _, k := range same {
			fmt.Fprintf(&b, "- `%s`\n", k)
		}
	}

	b.WriteString("\n## Only in v0\n\n")
	b.WriteString("The commands not rewritten yet, and the rows the rewrite leaves out.\n\n")
	writeGrouped(&b, onlyV0)
	return b.String(), nil
}

const header = `# Golden files: v0 and v1

<!-- Generated by ` + "`make -C v1 golden-diff`" + ` (internal/tools/goldendiff). Don't edit it by hand:
change a golden file or a note in internal/tools/goldendiff/notes.go, then regenerate. -->

How each golden file of the rewrite's suite (` + "`test/v1/local`, `v1/cmd/plumber`" + `) differs from
its namesake in the old CLI's suite (` + "`test/v0/local`" + `). Files are compared on the command,
the exit code, stdout and stderr, decoded from YAML, so a change of quoting style doesn't show.
` + "`␛`" + ` marks an ANSI escape: the rewrite's logs are colored.

This document, like ` + "`test/v0`" + `, goes away at the switch (step 15 of
[project-structure.md](project-structure.md#rewrite-order)).

`

// checkNotes fails when a changed or new golden has no note, or a note names
// a golden that is neither.
func checkNotes(keys []string, notes map[string]string) error {
	var missing, stale []string
	for _, k := range keys {
		if notes[k] == "" {
			missing = append(missing, k)
		}
	}
	for k := range notes {
		if !slices.Contains(keys, k) {
			stale = append(stale, k)
		}
	}
	slices.Sort(stale)
	if len(missing) > 0 || len(stale) > 0 {
		return fmt.Errorf("notes.go: add a note for %v, remove the note for %v", missing, stale)
	}
	return nil
}

func equal(a, b golden) bool {
	return a.Command == b.Command && a.Exit == b.Exit && a.Stdout == b.Stdout && a.Stderr == b.Stderr &&
		maps.Equal(a.Files, b.Files)
}

func writeChanged(b *strings.Builder, key string, old, cur golden, note string) {
	fmt.Fprintf(b, "\n### %s\n\n", key)
	if old.Command == cur.Command {
		fmt.Fprintf(b, "`$ %s`", cur.Command)
	} else {
		fmt.Fprintf(b, "`$ %s` (v0: `$ %s`)", cur.Command, old.Command)
	}
	if old.Exit == cur.Exit {
		fmt.Fprintf(b, ", exit %d\n\n", cur.Exit)
	} else {
		fmt.Fprintf(b, ", exit %d (v0: %d)\n\n", cur.Exit, old.Exit)
	}
	fmt.Fprintf(b, "%s\n", note)
	for _, f := range []struct{ name, old, cur string }{
		{"stdout", old.Stdout, cur.Stdout},
		{"stderr", old.Stderr, cur.Stderr},
	} {
		if f.old == f.cur {
			continue
		}
		fmt.Fprintf(b, "\n%s:\n\n```diff\n", f.name)
		for _, l := range collapse(diffLines(lines(f.old), lines(f.cur))) {
			b.WriteString(strings.TrimRight(fmt.Sprintf("%c %s", l.op, visible(l.text)), " ") + "\n")
		}
		b.WriteString("```\n")
	}
	for _, p := range slices.Sorted(maps.Keys(cur.Files)) {
		if old.Files[p] != cur.Files[p] {
			fmt.Fprintf(b, "\nThe file `%s` differs.\n", p)
		}
	}
}

func writeAdded(b *strings.Builder, key string, cur golden, note string) {
	fmt.Fprintf(b, "\n### %s\n\n`$ %s`, exit %d\n\n%s\n", key, cur.Command, cur.Exit, note)
	for _, f := range []struct{ name, text string }{{"stdout", cur.Stdout}, {"stderr", cur.Stderr}} {
		if f.text == "" {
			continue
		}
		fmt.Fprintf(b, "\n%s:\n\n```\n%s", f.name, visible(f.text))
		if !strings.HasSuffix(f.text, "\n") {
			b.WriteString("\n")
		}
		b.WriteString("```\n")
	}
}

// writeGrouped lists keys under their test, one line per test.
func writeGrouped(b *strings.Builder, keys []string) {
	if len(keys) == 0 {
		b.WriteString("None.\n")
		return
	}
	groups := map[string][]string{}
	for _, k := range keys {
		test, row, _ := strings.Cut(k, "/")
		groups[test] = append(groups[test], "`"+row+"`")
	}
	for _, test := range slices.Sorted(maps.Keys(groups)) {
		fmt.Fprintf(b, "- %s (%d): %s\n", test, len(groups[test]), strings.Join(groups[test], ", "))
	}
}

// visible shows the escape character as ␛.
func visible(s string) string {
	return strings.ReplaceAll(s, "\x1b", "␛")
}

func lines(s string) []string {
	if s == "" {
		return nil
	}
	return strings.Split(strings.TrimSuffix(s, "\n"), "\n")
}

// line is one line of a diff: op is ' ' (in both), '-' (v0 only) or '+'
// (v1 only), or '…' for a run of unchanged lines left out.
type line struct {
	op   rune
	text string
}

// diffLines returns the line diff of a and b, from their longest common
// subsequence. Golden outputs are small, so the quadratic table is fine.
func diffLines(a, b []string) []line {
	lcs := make([][]int, len(a)+1)
	for i := range lcs {
		lcs[i] = make([]int, len(b)+1)
	}
	for i, ai := range slices.Backward(a) {
		for j, bj := range slices.Backward(b) {
			if ai == bj {
				lcs[i][j] = lcs[i+1][j+1] + 1
			} else {
				lcs[i][j] = max(lcs[i+1][j], lcs[i][j+1])
			}
		}
	}
	var out []line
	i, j := 0, 0
	for i < len(a) && j < len(b) {
		switch {
		case a[i] == b[j]:
			out = append(out, line{' ', a[i]})
			i++
			j++
		case lcs[i+1][j] >= lcs[i][j+1]:
			out = append(out, line{'-', a[i]})
			i++
		default:
			out = append(out, line{'+', b[j]})
			j++
		}
	}
	for ; i < len(a); i++ {
		out = append(out, line{'-', a[i]})
	}
	for ; j < len(b); j++ {
		out = append(out, line{'+', b[j]})
	}
	return out
}

// context is the number of unchanged lines kept around a change.
const context = 2

// collapse replaces a run of unchanged lines longer than 2*context with its
// first and last context lines around a '…' line.
func collapse(diff []line) []line {
	var out []line
	for i := 0; i < len(diff); {
		if diff[i].op != ' ' {
			out = append(out, diff[i])
			i++
			continue
		}
		j := i
		for j < len(diff) && diff[j].op == ' ' {
			j++
		}
		if run := diff[i:j]; len(run) > 2*context+1 {
			out = append(out, run[:context]...)
			out = append(out, line{'…', fmt.Sprintf("%d unchanged lines", len(run)-2*context)})
			out = append(out, run[len(run)-context:]...)
		} else {
			out = append(out, run...)
		}
		i = j
	}
	return out
}
